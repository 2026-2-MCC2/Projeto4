-- Sistema real de administração: logs de auditoria e tickets de suporte.
-- Rode UMA vez no SQL Editor do Supabase (idempotente, pode rodar de novo).
-- Obs.: o "nível de acesso" dos admins (master/suporte) já existe na tabela
-- administradores (coluna nivel_acesso, criada no schema.sql original) —
-- não precisa de migração nova pra isso, só passamos a usar de verdade.

-- ===== LOGS DE AUDITORIA =====
CREATE TABLE IF NOT EXISTS logs_auditoria (
  id_log     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INT REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  acao       VARCHAR(60) NOT NULL,
  detalhe    TEXT,
  criado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_logs_auditoria_criado_em ON logs_auditoria(criado_em DESC);
ALTER TABLE logs_auditoria ENABLE ROW LEVEL SECURITY;

-- ===== TICKETS DE SUPORTE =====
-- categoria usa o vocabulário real do TrocaTicket (nada de "custódia/escrow",
-- isso não existe no nosso domínio: eventos, propostas, cadastro, financeiro).
CREATE TABLE IF NOT EXISTS tickets_suporte (
  id_ticket     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario    INT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  assunto       VARCHAR(150) NOT NULL,
  categoria     VARCHAR(30) NOT NULL
                CHECK (categoria IN ('evento','proposta','cadastro','financeiro','outro')),
  prioridade    VARCHAR(10) NOT NULL DEFAULT 'media'
                CHECK (prioridade IN ('alta','media','baixa')),
  status        VARCHAR(20) NOT NULL DEFAULT 'aberto'
                CHECK (status IN ('aberto','em_andamento','resolvido','fechado')),
  criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_tickets_suporte_status ON tickets_suporte(status);
ALTER TABLE tickets_suporte ENABLE ROW LEVEL SECURITY;

-- Conversa dentro de cada ticket (pergunta do usuário + respostas do suporte)
CREATE TABLE IF NOT EXISTS ticket_mensagens (
  id_mensagem INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ticket   INT NOT NULL REFERENCES tickets_suporte(id_ticket) ON DELETE CASCADE,
  id_usuario  INT REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  mensagem    TEXT NOT NULL,
  criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ticket_mensagens_ticket ON ticket_mensagens(id_ticket);
ALTER TABLE ticket_mensagens ENABLE ROW LEVEL SECURITY;
