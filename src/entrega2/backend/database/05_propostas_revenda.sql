-- Contrapropostas de preço em anúncios de revenda.
-- Rode UMA vez no SQL Editor do Supabase (rodar de novo não causa problema).

-- Nome propostas_revenda (não "propostas") de propósito: esse nome já é usado
-- pelo módulo de cotação organizador/fornecedor (RF07/08), que é algo totalmente
-- diferente (proposta de orçamento, não de preço de revenda entre clientes).
CREATE TABLE IF NOT EXISTS propostas_revenda (
  id_proposta    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revenda     INT NOT NULL REFERENCES revendas(id_revenda),
  id_cliente     INT NOT NULL REFERENCES clientes(id_cliente), -- quem propôs (o comprador)
  preco_proposto NUMERIC(10,2) NOT NULL CHECK (preco_proposto > 0),
  status         VARCHAR(20) NOT NULL DEFAULT 'pendente'
                 CHECK (status IN ('pendente','aceita','recusada','cancelada')),
  criado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_propostas_revenda_revenda ON propostas_revenda(id_revenda);
CREATE INDEX IF NOT EXISTS idx_propostas_revenda_cliente ON propostas_revenda(id_cliente);

ALTER TABLE propostas_revenda ENABLE ROW LEVEL SECURITY;