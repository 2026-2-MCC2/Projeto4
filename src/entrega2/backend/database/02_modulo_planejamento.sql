ALTER TABLE eventos ADD CONSTRAINT ck_eventos_periodo
  CHECK (data_fim IS NULL OR data_fim >= data);

-- ===== EVENTOS: novos status (rascunho → aberto → fechado, ou cancelado) =====
ALTER TABLE eventos DROP CONSTRAINT IF EXISTS eventos_status_check;
UPDATE eventos SET status = 'rascunho' WHERE status = 'planejado';
UPDATE eventos SET status = 'fechado'  WHERE status IN ('confirmado', 'encerrado');
ALTER TABLE eventos ALTER COLUMN status SET DEFAULT 'rascunho';
ALTER TABLE eventos ADD CONSTRAINT eventos_status_check
  CHECK (status IN ('rascunho', 'aberto', 'fechado', 'cancelado'));

-- ===== ITENS DE CUSTO (o que o evento precisa contratar) =====
CREATE TABLE IF NOT EXISTS itens_custo (
  id_item   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento INT NOT NULL REFERENCES eventos(id_evento) ON DELETE CASCADE,
  nome      VARCHAR(100) NOT NULL,
  categoria VARCHAR(30)  NOT NULL
            CHECK (categoria IN ('iluminacao','alimentacao','bebida','seguranca','estrutura','outros')),
  descricao TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_itens_custo_evento ON itens_custo(id_evento);

-- ===== CUSTOS DO EVENTO (que não vêm de propostas) =====
-- por_participante = TRUE  → o valor é por pessoa (ex.: R$ 3 de taxa por ingresso)
-- por_participante = FALSE → o valor é o total (ex.: R$ 5.000 de alvará)
CREATE TABLE IF NOT EXISTS custos_evento (
  id_custo         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento        INT NOT NULL REFERENCES eventos(id_evento) ON DELETE CASCADE,
  tipo             VARCHAR(20)  NOT NULL CHECK (tipo IN ('fiscal','operacional','variavel','outro')),
  descricao        VARCHAR(150) NOT NULL,
  valor            NUMERIC(12,2) NOT NULL CHECK (valor >= 0),
  por_participante BOOLEAN NOT NULL DEFAULT FALSE,
  criado_em        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_custos_evento_evento ON custos_evento(id_evento);

-- ===== PROPOSTAS: agora ligadas a um item de custo =====
ALTER TABLE propostas ADD COLUMN IF NOT EXISTS id_item
  INT REFERENCES itens_custo(id_item) ON DELETE CASCADE;
ALTER TABLE propostas ADD COLUMN IF NOT EXISTS descricao   TEXT;
ALTER TABLE propostas ADD COLUMN IF NOT EXISTS validade    DATE;
ALTER TABLE propostas ADD COLUMN IF NOT EXISTS observacoes TEXT;

ALTER TABLE propostas DROP CONSTRAINT IF EXISTS propostas_status_check;
ALTER TABLE propostas ADD CONSTRAINT propostas_status_check
  CHECK (status IN ('enviada', 'aceita', 'recusada', 'cancelada'));

-- no máximo UMA proposta aceita por item
CREATE UNIQUE INDEX IF NOT EXISTS uq_proposta_aceita_por_item
  ON propostas(id_item) WHERE status = 'aceita';

-- cada fornecedor tem no máximo UMA proposta ativa por item (para mudar, edite a existente)
CREATE UNIQUE INDEX IF NOT EXISTS uq_proposta_ativa_por_fornecedor
  ON propostas(id_item, id_fornecedor) WHERE status IN ('enviada', 'aceita');

