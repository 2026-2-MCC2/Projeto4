ALTER TABLE eventos ADD CONSTRAINT ck_eventos_publico
  CHECK (publico_minimo IS NULL OR (publico_minimo > 0 AND publico_maximo >= publico_minimo));

ALTER TABLE eventos DROP CONSTRAINT IF EXISTS ck_eventos_margem;
ALTER TABLE eventos ADD CONSTRAINT ck_eventos_margem
  CHECK (margem_lucro >= 0 AND margem_lucro < 100);

