-- ===== EVENTOS: campos de publicação para o público =====
ALTER TABLE eventos ADD COLUMN IF NOT EXISTS categoria            VARCHAR(30);
ALTER TABLE eventos ADD COLUMN IF NOT EXISTS imagem_url           VARCHAR(255);
ALTER TABLE eventos ADD COLUMN IF NOT EXISTS preco_ingresso       NUMERIC(10,2);
ALTER TABLE eventos ADD COLUMN IF NOT EXISTS ingressos_total      INT;
ALTER TABLE eventos ADD COLUMN IF NOT EXISTS ingressos_vendidos   INT NOT NULL DEFAULT 0;
ALTER TABLE eventos ADD COLUMN IF NOT EXISTS publicado_para_venda BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE eventos DROP CONSTRAINT IF EXISTS ck_eventos_publicacao;
ALTER TABLE eventos ADD CONSTRAINT ck_eventos_publicacao
  CHECK (
    publicado_para_venda = false
    OR (preco_ingresso IS NOT NULL AND preco_ingresso > 0
        AND ingressos_total IS NOT NULL AND ingressos_total > 0
        AND ingressos_vendidos <= ingressos_total)
  );

-- ===== COMPRAS (um lote de N ingressos comprados de uma vez, por um cliente) =====
CREATE TABLE IF NOT EXISTS compras (
  id_compra     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente    INT NOT NULL REFERENCES clientes(id_cliente),
  id_evento     INT NOT NULL REFERENCES eventos(id_evento),
  quantidade    INT NOT NULL CHECK (quantidade > 0),
  valor_unitario NUMERIC(10,2) NOT NULL CHECK (valor_unitario > 0),
  valor_total   NUMERIC(10,2) NOT NULL CHECK (valor_total > 0),
  status        VARCHAR(20) NOT NULL DEFAULT 'confirmada'
                CHECK (status IN ('confirmada','cancelada','revendida')),
  criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_compras_cliente ON compras(id_cliente);
CREATE INDEX IF NOT EXISTS idx_compras_evento  ON compras(id_evento);

-- ===== REVENDAS (um lote de uma compra anunciado por um novo preço) =====
CREATE TABLE IF NOT EXISTS revendas (
  id_revenda     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_compra      INT NOT NULL UNIQUE REFERENCES compras(id_compra),
  preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario > 0),
  status         VARCHAR(20) NOT NULL DEFAULT 'disponivel'
                 CHECK (status IN ('disponivel','vendida','cancelada')),
  criado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_revendas_status ON revendas(status);

-- ===== SEGURANÇA =====
ALTER TABLE compras  ENABLE ROW LEVEL SECURITY;
ALTER TABLE revendas ENABLE ROW LEVEL SECURITY;
